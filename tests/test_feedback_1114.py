import csv
import io
import json
from pathlib import Path

import pytest

from test_ledgersight import golden_run, make_user

ROOT = Path(__file__).resolve().parents[1]
HTML = (ROOT / "ledgersight" / "static" / "index.html").read_text(encoding="utf-8")
JS = (ROOT / "ledgersight" / "static" / "avocet.js").read_text(encoding="utf-8")
WS = "/v1/workspaces/client-a"
HEADER_FIELDS = ("report_name", "report_id", "client", "period", "generated_by", "generated_at")


@pytest.fixture(scope="module")
def cpa_run():
    c = make_user("fb1114-cpa@demo.test", "owner_reviewer", ["client-a"])
    return c, golden_run(c)


def _csv_head(body: bytes) -> dict:
    rows = list(csv.reader(io.StringIO(body.decode("utf-8-sig"))))
    head = {}
    for r in rows:
        if not r:
            break  # header block ends at the first blank line
        if len(r) >= 2:
            head.setdefault(r[0], r[1])
    return rows, head


@pytest.mark.parametrize("path,name", [
    ("/runs/{rid}/reports/finance.csv", "Finance Reconciliation Report"),
    ("/runs/{rid}/reports/governance.csv", "TrustOps Governance Report"),
    ("/runs/{rid}/export.csv", "Reconciliation Review Export"),
    ("/audit-trail.csv", "Audit Trail Report"),
])
def test_every_csv_download_starts_with_the_report_name_and_header(cpa_run, path, name):
    c, run = cpa_run
    r = c.get(WS + path.format(rid=run["id"]))
    assert r.status_code == 200 and "attachment" in r.headers["content-disposition"]
    rows, head = _csv_head(r.content)
    assert rows[0] == ["Report", name]
    assert head.get("Report ID") and head.get("Client") == "Client 1" and head.get("Period")
    assert head.get("Generated by") and head.get("Generated at (UTC)")


def test_review_csv_keeps_its_table_after_the_header(cpa_run):
    c, run = cpa_run
    rows, head = _csv_head(c.get(f"{WS}/runs/{run['id']}/export.csv").content)
    assert head["Run ID"] == run["id"] and head["Report ID"] == f"REV-{run['id']}"
    table = rows[rows.index([]) + 1:]
    assert table[0][:3] == ["client", "run_id", "record"] and any(r[4] == "HB001" for r in table[1:])


@pytest.mark.parametrize("path,name", [
    ("/runs/{rid}/reports/finance.json", "Finance Reconciliation Report"),
    ("/runs/{rid}/reports/governance.json", "TrustOps Governance Report"),
    ("/runs/{rid}/review-pack.json", "Reconciliation Review Pack"),
    ("/audit-trail.json", "Audit Trail Report"),
])
def test_every_json_download_starts_with_a_header(cpa_run, path, name):
    c, run = cpa_run
    r = c.get(WS + path.format(rid=run["id"]))
    assert r.status_code == 200 and "attachment" in r.headers.get("content-disposition", "")
    d = json.loads(r.content)
    assert list(d.keys())[0] in ("report", "header") and d["header"]["report_name"] == name
    assert all(d["header"].get(k) for k in HEADER_FIELDS), d["header"]


def test_on_screen_report_preview_is_not_a_download(cpa_run):
    c, run = cpa_run
    r = c.get(f"{WS}/runs/{run['id']}/reports/finance.json?preview=1")
    assert r.status_code == 200 and "content-disposition" not in r.headers


