KINDS = ("finance", "governance")


def money(c) -> str:
    return "" if c is None else f"{c / 100:.2f}"


def _section(title, columns, rows, note=None):
    return {"title": title, "columns": columns, "rows": [[("" if v is None else v) for v in r] for r in rows],
            **({"note": note} if note else {})}


