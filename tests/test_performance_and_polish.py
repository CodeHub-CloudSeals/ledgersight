def test_evidence_summary_matches_the_full_trail_and_is_small(cpa):
    golden_run(cpa)
    full = cpa.get(WS + "/evidence").json()
    s = cpa.get(WS + "/evidence/summary").json()
    for k in ("ALLOW", "ESCALATE", "DENY"):
        assert s["counts"][k] == sum(str(e["policy_decision"]).startswith(k) for e in full["events"])
    assert s["verification"]["state"] == full["verification"]["state"] == "PASS"
    assert len(s["recent"]) <= 7 and all(e["action"] not in ("workspace.read", "export.read", "query.ask") for e in s["recent"])
    small = len(cpa.get(WS + "/evidence/summary").content)
    assert small * 5 < len(cpa.get(WS + "/evidence").content)  # far smaller than the whole trail


