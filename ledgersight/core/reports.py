"""Finance and governance reports for one reconciliation run, in several formats.

Both reports carry the same run_id, so a finance figure can be traced to the
agent steps, policy decisions and approvals behind it. Every report is a
generic structure (summary + titled tables), so one set of renderers produces
JSON, CSV, Excel and PDF for any report.
"""
from __future__ import annotations

import csv
import io
import json
import re
import textwrap
from collections import Counter

FORMATS = {"json": "application/json", "csv": "text/csv; charset=utf-8",
           "xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "pdf": "application/pdf"}
KINDS = ("finance", "governance")


def money(c) -> str:
    return "" if c is None else f"{c / 100:.2f}"


def _section(title, columns, rows, note=None):
    return {"title": title, "columns": columns, "rows": [[("" if v is None else v) for v in r] for r in rows],
            **({"note": note} if note else {})}


# ---- builders ----------------------------------------------------------------
def finance_report(*, client: dict, run: dict, inputs: dict, generated_by: str, generated_at: str) -> dict:
    r = run["result"]
    exc = r["exceptions"]
    open_ = [e for e in exc if e["status"] in ("OPEN", "RETURNED")]
    residual = sum(e.get("residual_cents") or 0 for e in exc if e["type"] == "PARTIAL_RECEIPT")
    by_type = Counter(e["type"] for e in exc)
    summary = [
        ["Report", "Finance Reconciliation Report"], ["Produced by", "LedgerSight · AG-05 Report Composer"],
        ["Client", client["name"]], ["Period", client["period"]], ["Run ID", run["id"]],
        ["Trace ID", run.get("trace_id", "")], ["Engine", r["engine_version"]],
        ["Bank net movement (USD)", money(r["bank_net_cents"])], ["Ledger net movement (USD)", money(r["ledger_net_cents"])],
        ["Variance (USD)", money(r["variance_cents"])], ["Unexplained variance (USD)", money(r["unexplained_variance_cents"])],
        ["Matched automatically", len(r["matches"])], ["Exceptions raised", len(exc)], ["Awaiting review", len(open_)],
        ["Outstanding on partial receipts (USD)", money(residual)],
        ["Generated by", generated_by], ["Generated at (UTC)", generated_at],
        ["Boundary", "Read-only review output. Nothing was posted to any ledger, bank or client."],
    ]
    return {
        "report": "finance", "title": "Finance Reconciliation Report", "report_id": f"FIN-{run['id']}", "run_id": run["id"],
        "summary": summary,
        "sections": [
            _section("Source inputs", ["Source", "Rows", "SHA-256"], [[k, v["rows"], v["sha256"]] for k, v in inputs.items()]),
            _section("Exceptions by type", ["Type", "Count"], sorted(by_type.items())),
            _section("Exceptions and reviewer status",
                     ["ID", "Type", "Bank line", "Ledger line", "Amount (USD)", "Still owed (USD)", "Reason", "Status",
                      "Reviewer", "Approval ID"],
                     [[e["id"], e["type"], e["bank_id"], e["ledger_id"], money(e["amount_cents"]), money(e.get("residual_cents")),
                       e["why"], e["status"], e.get("reviewer"), e.get("approval_id")] for e in exc]),
            _section("Automatic matches", ["Bank line", "Ledger line", "Amount (USD)", "Rule", "Why"],
                     [[m["bank_id"], m["ledger_id"], money(m["amount_cents"]), m["rule_id"], m["why"]] for m in r["matches"]]),
        ],
    }


def governance_report(*, client: dict, run: dict, events: list[dict], verification: dict, policies: dict,
                      policy_version: str, key_id: str, generated_by: str, generated_at: str) -> dict:
    counts = Counter(str(e.get("policy_decision") or "").split(":")[0] for e in events)
    run_events = [e for e in events if e.get("run_id") == run["id"]]
    used = sorted({e["policy_id"] for e in events if e.get("policy_id")})
    exc = run["result"]["exceptions"]
    decided = [e for e in exc if e["status"] != "OPEN"]
    denied = [e for e in events if str(e.get("policy_decision") or "").startswith("DENY")]
    summary = [
        ["Report", "TrustOps Governance Report"], ["Produced by", "TrustOps (composed by AG-05)"],
        ["Client", client["name"]], ["Period", client["period"]], ["Run ID", run["id"]],
        ["Trace ID", run.get("trace_id", "")], ["Policy set version", policy_version],
        ["Agents in this run", len(run.get("workflow", []))],
        ["ALLOW decisions", counts.get("ALLOW", 0)], ["ESCALATE decisions", counts.get("ESCALATE", 0)],
        ["DENY decisions", counts.get("DENY", 0)], ["Human decisions recorded", len(decided)],
        ["Evidence verification", f"{verification['state']}: {verification['reason']} ({verification['checked']} events)"],
        ["Signing key", key_id], ["Generated by", generated_by], ["Generated at (UTC)", generated_at],
    ]
    return {
        "report": "governance", "title": "TrustOps Governance Report", "report_id": f"GOV-{run['id']}", "run_id": run["id"],
        "summary": summary,
        "sections": [
            _section("Agent steps in this run",
                     ["Step", "Agent", "Name", "Action", "Decision", "Policy", "Rows in", "Rows out", "Duration (ms)", "Step ID"],
                     [[i + 1, s["agent"], s["name"], s["action"], s["decision"], s["policy_id"], s["rows_in"], s["rows_out"],
                       s["duration_ms"], s["step_id"]] for i, s in enumerate(run.get("workflow", []))]),
            _section("Exception routing", ["Exception", "Type", "TrustOps decision", "Policy", "Required role", "Status"],
                     [[e["id"], e["type"], (e.get("trustops") or {}).get("decision"), (e.get("trustops") or {}).get("policy_id"),
                       (e.get("trustops") or {}).get("required_role_label") or (e.get("trustops") or {}).get("required_role"),
                       e["status"]] for e in exc]),
            _section("Human approvals", ["Exception", "Decision", "Reviewer", "Proposed by", "Approval ID", "Decided at (UTC)", "Note"],
                     [[e["id"], e["status"], e.get("reviewer"), e.get("proposed_by") or "agent:recon", e.get("approval_id"),
                       e.get("reviewed_at"), e.get("review_note")] for e in decided]),
            _section("Denied actions", ["Time (UTC)", "Actor", "Actor type", "Action", "Decision", "Policy"],
                     [[e["timestamp_utc"], e["actor_id"], e["actor_type"], e["action"], e["policy_decision"], e.get("policy_id")]
                      for e in denied]),
            _section("Policies applied", ["Policy", "Name", "Rule version", "Effect", "Rule"],
                     [[p, policies[p]["name"], policies[p]["version"], policies[p]["effect"], policies[p]["rule"]] for p in used if p in policies]),
            _section("Run events (signed)", ["Time (UTC)", "Actor", "Action", "Decision", "Policy", "Event hash"],
                     [[e["timestamp_utc"], e["actor_id"], e["action"], e["policy_decision"], e.get("policy_id"), e["event_hash"]]
                      for e in run_events]),
        ],
    }


# ---- renderers -----------------------------------------------------------------
_NUM = re.compile(r"^-?\d+(\.\d+)?$")


def _safe(v):
    """Spreadsheet-injection guard: text that a spreadsheet would run as a formula is quoted."""
    if isinstance(v, str) and v[:1] in ("=", "+", "-", "@") and not _NUM.match(v):
        return "'" + v
    return v


def to_json(rep: dict) -> bytes:
    return json.dumps(rep, indent=2, default=str).encode()


def to_csv(rep: dict) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow([rep["title"]])
    for k, v in rep["summary"]:
        w.writerow([k, _safe(v)])
    for s in rep["sections"]:
        w.writerow([])
        w.writerow([s["title"]])
        w.writerow(s["columns"])
        for r in s["rows"]:
            w.writerow([_safe(v) for v in r])
    return buf.getvalue().encode("utf-8-sig")


def to_xlsx(rep: dict) -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Font

    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"

    def put(sheet, row, vals, bold=False):
        for col, v in enumerate(vals, start=1):
            if isinstance(v, str) and _NUM.match(v):
                v = float(v)
            c = sheet.cell(row=row, column=col, value=v)
            if isinstance(v, str) and v.startswith("="):
                c.data_type = "s"  # text, never a formula
            if bold:
                c.font = Font(bold=True)

    put(ws, 1, [rep["title"]], bold=True)
    for i, (k, v) in enumerate(rep["summary"], start=3):
        put(ws, i, [k, v])
    ws.column_dimensions["A"].width, ws.column_dimensions["B"].width = 38, 70
    used = set()
    for s in rep["sections"]:
        name = re.sub(r"[\[\]:*?/\\]", "", s["title"])[:31]
        while name in used:
            name = name[:29] + str(len(used))
        used.add(name)
        sh = wb.create_sheet(name)
        put(sh, 1, s["columns"], bold=True)
        for i, r in enumerate(s["rows"], start=2):
            put(sh, i, r)
        for col, h in enumerate(s["columns"], start=1):
            width = max([len(str(h))] + [len(str(r[col - 1])) for r in s["rows"]])
            sh.column_dimensions[sh.cell(row=1, column=col).column_letter].width = min(60, max(10, width + 2))
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def to_pdf(rep: dict) -> bytes:
    """Small self-contained PDF writer (standard fonts, landscape Letter). No extra dependency."""
    W, M = 792, 36  # landscape Letter width and margin, used to fit tables
    lines: list[tuple[str, float, str]] = []  # (font, size, text)
    lines.append(("F2", 15, rep["title"]))
    lines.append(("F1", 8, f"Report {rep['report_id']} · Run {rep['run_id']}"))
    lines.append(("F1", 6, ""))
    for k, v in rep["summary"]:
        for i, part in enumerate(textwrap.wrap(f"{k}: {v}", 150) or [""]):
            lines.append(("F1", 8.5, part if i == 0 else "    " + part))
    cw = 7 * 0.6  # Courier 7pt character width
    max_chars = int((W - 2 * M) / cw)
    for s in rep["sections"]:
        lines.append(("F1", 6, ""))
        lines.append(("F2", 11, s["title"]))
        if not s["rows"]:
            lines.append(("F1", 8.5, "None."))
            continue
        cols = s["columns"]
        nat = [max([len(str(c))] + [len(str(r[i])) for r in s["rows"]]) for i, c in enumerate(cols)]
        widths = nat[:]
        while sum(widths) + 2 * len(widths) > max_chars:  # shrink the widest column until the table fits
            j = widths.index(max(widths))
            widths[j] -= 1
            if widths[j] < 6:
                break

        def emit(cells):
            wrapped = [textwrap.wrap(str(c), w) or [""] for c, w in zip(cells, widths)]
            for n in range(max(len(x) for x in wrapped)):
                lines.append(("F3", 7, "  ".join((x[n] if n < len(x) else "").ljust(w) for x, w in zip(wrapped, widths))))
        emit(cols)
        lines.append(("F3", 7, "  ".join("-" * w for w in widths)))
        for r in s["rows"]:
            emit(r)

    return write_pdf(lines, footer=lambda i, n: f"{rep['report_id']} · run {rep['run_id']} · page {i} of {n}")


def write_pdf(lines: list[tuple[str, float, str]], *, footer=None, landscape=True, title: str = "",
              extra_ops: bytes = b"") -> bytes:
    """Minimal text PDF: lines of (font F1|F2|F3, size, text) with automatic paging. F1 Helvetica,
    F2 Helvetica-Bold, F3 Courier, F4 Courier-Bold. `extra_ops` are raw drawing operators added to page 1."""
    W, H = (792, 612) if landscape else (612, 792)
    M = 36 if landscape else 72
    pages, cur, y = [], [], H - M
    for font, size, text in lines:
        lead = size * 1.35
        if y - lead < M + 14:
            pages.append(cur); cur, y = [], H - M
        y -= lead
        cur.append((font, size, M, y, text))
    pages.append(cur)

    def esc(t: str) -> bytes:
        b = t.encode("cp1252", "replace")
        return b.replace(b"\\", b"\\\\").replace(b"(", b"\\(").replace(b")", b"\\)")

    objs: list[bytes] = []
    add = lambda b: objs.append(b) or len(objs)
    cat = add(b"")
    pages_id = add(b"")
    fonts = [add(f"<< /Type /Font /Subtype /Type1 /BaseFont /{n} /Encoding /WinAnsiEncoding >>".encode())
             for n in ("Helvetica", "Helvetica-Bold", "Courier", "Courier-Bold")]
    kids = []
    for i, pg in enumerate(pages, start=1):
        body = (extra_ops if i == 1 else b"") + b"".join(
            b"BT /%s %.1f Tf %.1f %.1f Td (%s) Tj ET\n" % (f.encode(), s, x, yy, esc(t)) for f, s, x, yy, t in pg if t)
        if footer:
            body += b"BT /F1 7 Tf %d %d Td (%s) Tj ET\n" % (M, M - 12, esc(footer(i, len(pages))))
        content = add(b"<< /Length %d >>\nstream\n" % len(body) + body + b"\nendstream")
        kids.append(add(b"<< /Type /Page /Parent %d 0 R /MediaBox [0 0 %d %d] /Contents %d 0 R "
                        b"/Resources << /Font << /F1 %d 0 R /F2 %d 0 R /F3 %d 0 R /F4 %d 0 R >> >> >>"
                        % (pages_id, W, H, content, *fonts)))
    objs[cat - 1] = b"<< /Type /Catalog /Pages %d 0 R >>" % pages_id
    if title:
        objs.append(b"<< /Title (%s) /Producer (LedgerSight) >>" % esc(title))
    objs[pages_id - 1] = b"<< /Type /Pages /Kids [%s] /Count %d >>" % (b" ".join(b"%d 0 R" % k for k in kids), len(kids))
    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for n, o in enumerate(objs, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % n + o + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1)
    out += b"".join(b"%010d 00000 n \n" % off for off in offsets)
    info = b" /Info %d 0 R" % len(objs) if title else b""
    out += b"trailer\n<< /Size %d /Root %d 0 R%s >>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, cat, info, xref)
    return bytes(out)


