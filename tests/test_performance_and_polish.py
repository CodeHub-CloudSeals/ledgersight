def test_audit_trail_exports_carry_report_name_and_header(cpa):
    run = golden_run(cpa)
    rows = list(csv.reader(io.StringIO(cpa.get(f"{WS}/runs/{run['id']}/export.csv").text)))
    head = {r[0]: r[1] for r in rows[1:10] if len(r) == 2}
    assert rows[0] == ["LedgerSight Review Export"] and head["Client"] and head["Period"] and head["Run ID"] == run["id"]
    assert head["Generated at (UTC)"] and head["Generated by"] == "perf@demo.test"
    assert any(r[:3] == ["client", "run_id", "record"] for r in rows)  # the data table follows the header
    pack = cpa.get(f"{WS}/runs/{run['id']}/review-pack.json").json()
    assert pack["title"] == "LedgerSight Signed Review Pack" and pack["run_id"] == run["id"] and pack["period"]
    assert list(pack)[:3] == ["report", "title", "report_id"]


def test_review_comments_are_kept_with_time(cpa):
    run = golden_run(cpa)
    e = next(x for x in run["result"]["exceptions"] if x["bank_id"] == "HB006")
    base = f"{WS}/runs/{run['id']}/exceptions/{e['id']}"
    p = cpa.post(base + "/proposals", headers=H, json={"note": "bill GP-5531 on file"}).json()
    assert p["proposed_at"] and p["proposal_note"] == "bill GP-5531 on file"
    other = make_user("perf-b@demo.test", "owner_reviewer", ["client-a"])
    d = other.post(base + "/decisions", headers=H, json={"decision": "ACCEPT", "note": "agreed"}).json()
    assert d["history"][-1]["note"] == "agreed" and d["reviewer"] == "perf-b@demo.test"
    assert "function decisionBox(x)" in JS and "function commentTrail(x)" in JS and "decisionBox(x), commentTrail(x)," in JS
    assert '"Comments & decisions"' in JS and "No comment added" in JS
    # the box must not reuse the button classes .ok/.bad (white text on a green button)
    assert '(ok ? "xdec-ok" : "xdec-bad")' in JS and ".xdec.xdec-bad{" in CSS


