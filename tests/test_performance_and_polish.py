def test_signature_check_is_cached_but_rechecks_after_changes(cpa, monkeypatch):
    golden_run(cpa)
    from ledgersight.core import evidence
    calls = []
    real = evidence.verify
    monkeypatch.setattr(evidence, "verify", lambda ev, key: calls.append(len(ev)) or real(ev, key))
    cpa.get(WS + "/evidence/summary"); n1 = len(calls)
    cpa.get(WS + "/evidence/summary")
    assert len(calls) == n1  # unchanged chain: not re-verified
    cpa.post(WS + "/actions/attempt", headers=H, json={"action": "ledger.post"})  # adds a DENY event
    s = cpa.get(WS + "/evidence/summary").json()
    assert len(calls) == n1 + 1 and s["verification"]["state"] == "PASS"  # new event: verified again
    t = cpa.post(WS + "/evidence/tamper-check", headers=H).json()
    assert t["verification"]["state"] == "FAIL" and t["original_chain"]["state"] == "PASS"  # tampering still detected


