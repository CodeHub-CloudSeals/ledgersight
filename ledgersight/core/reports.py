def finance_report(*, client: dict, run: dict, inputs: dict, generated_by: str, generated_at: str) -> dict:
    r = run["result"]
    exc = r["exceptions"]
    open_ = [e for e in exc if e["status"] in ("OPEN", "RETURNED")]
    residual = sum(e.get("residual_cents") or 0 for e in exc if e["type"] == "PARTIAL_RECEIPT")
    by_type = Counter(e["type"] for e in exc)
    status_of = lambda e: e.get("client_status") or e["type"]
    totals: dict[str, list[int]] = {"MATCHED": [len(r["matches"]), sum(abs(m["amount_cents"]) for m in r["matches"])]}
    for e in exc:
        t = totals.setdefault(status_of(e), [0, 0])
        t[0] += 1
        t[1] += abs(e["amount_cents"])
    amt = lambda k: money(totals.get(k, [0, 0])[1])
    reviews = [e for e in exc if e["type"] in ("TAX_REVIEW", "FX_REVIEW")]
    summary = [
        ["Report", "Finance Reconciliation Report"], ["Produced by", "LedgerSight · AG-05 Report Composer"],
        ["Client", client["name"]], ["Period", client["period"]], ["Run ID", run["id"]],
        ["Trace ID", run.get("trace_id", "")], ["Engine", r["engine_version"]],
        ["Bank net movement (USD)", money(r["bank_net_cents"])], ["Ledger net movement (USD)", money(r["ledger_net_cents"])],
        ["Variance (USD)", money(r["variance_cents"])], ["Unexplained variance (USD)", money(r["unexplained_variance_cents"])],
        ["Matched automatically", len(r["matches"])], ["Exceptions raised", len(exc)], ["Awaiting review", len(open_)],
        ["Outstanding on partial receipts (USD)", money(residual)],
        ["Matched amount (USD)", amt("MATCHED")], ["Partial receipts amount (USD)", amt("PARTIAL")],
        ["Unmatched amount (USD)", amt("UNMATCHED")], ["Possible duplicate amount (USD)", amt("DUPLICATE")],
        ["Tax review items", by_type.get("TAX_REVIEW", 0)], ["FX review items", by_type.get("FX_REVIEW", 0)],
        ["Data", "Synthetic demo data"],
        ["Generated by", generated_by], ["Generated at (UTC)", generated_at],
        ["Boundary", "Read-only review output. Nothing was posted to any ledger, bank or client. No tax was computed, filed or paid."],
    ]
    return {
        "report": "finance", "title": "Finance Reconciliation Report", "report_id": f"FIN-{run['id']}", "run_id": run["id"],
        "summary": summary,
        "sections": [
            _section("Source inputs", ["Source", "Rows", "SHA-256"], [[k, v["rows"], v["sha256"]] for k, v in inputs.items()]),
            _section("Exceptions by type", ["Type", "Count"], sorted(by_type.items())),
            _section("Exceptions and reviewer status",
                     ["ID", "Type", "Bank line", "Ledger line", "Amount (USD)", "Still owed (USD)", "Reason", "Status",
                      "Reviewer", "Approval ID", "Case", "Client status"],
                     [[e["id"], e["type"], e["bank_id"], e["ledger_id"], money(e["amount_cents"]), money(e.get("residual_cents")),
                       e["why"], e["status"], e.get("reviewer"), e.get("approval_id"), e.get("case_id"), _client_status(e)]
                      for e in exc]),
            _section("Automatic matches", ["Bank line", "Ledger line", "Amount (USD)", "Rule", "Why"],
                     [[m["bank_id"], m["ledger_id"], money(m["amount_cents"]), m["rule_id"], m["why"]] for m in r["matches"]]),
            _section("Totals by status", ["Status", "Items", "Amount (USD)"],
                     [[k, v[0], money(v[1])] for k, v in sorted(totals.items())],
                     note="Amounts are absolute values in USD as recorded in the source files; nothing is converted."),
            _section("Source totals", ["Source", "File", "Rows", "Currency", "Net (USD)"],
                     [[k, v.get("filename"), v["rows"], ", ".join(v.get("currency") or []), money(v.get("net_cents"))]
                      for k, v in inputs.items()],
                     note="Bank and ledger: net movement. Open invoices and vendor bills: open balance of USD rows; "
                          "rows in other currencies are listed but never converted."),
            _section("Tax and FX review items", ["Case", "Type", "Facts from the source files", "Missing inputs / reason",
                                                 "Policy", "Required role", "Status"],
                     [[e.get("case_id"), e["type"], "; ".join(f"{k}: {v}" for k, v in (e.get("facts") or {}).items() if v),
                       ", ".join(e.get("missing_inputs") or []) or e.get("reason_code") or "",
                       (e.get("trustops") or {}).get("policy_id"),
                       (e.get("trustops") or {}).get("required_role_label"), e["status"]] for e in reviews],
                     note="Review flags only. No tax liability, tax amount or exchange rate is asserted."),
            _section("CPA next steps", ["Case", "Client status", "Next step", "Owner"],
                     [[e.get("case_id") or e["id"], _client_status(e), e.get("suggestion") or "CPA review",
                       (e.get("trustops") or {}).get("required_role_label") or "CPA reviewer"] for e in open_]),
        ],
    }


def _client_status(e: dict) -> str:
    """Client-facing status. A case is only ever shown as resolved once a named person has decided it."""
    if e["status"] in ("ACCEPTED", "REJECTED"):
        return f"{e['status']} (by {e.get('reviewer')})"
    return e.get("client_status") or e["type"]


