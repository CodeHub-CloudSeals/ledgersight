"""Finance and governance reports for one reconciliation run, in several formats.

Both reports carry the same run_id, so a finance figure can be traced to the
agent steps, policy decisions and approvals behind it. Every report is a
generic structure (summary + titled tables), so one set of renderers produces
JSON, CSV, Excel and PDF for any report.
"""
